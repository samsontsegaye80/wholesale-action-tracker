/**
 * Opens email client via mailto or Gmail direct web compose.
 */
export function openDirectEmailComposer(
  recipient: string = TARGET_EMAIL,
  subject: string,
  body: string
) {
  // Construct Gmail web composer URL for reliable browser dispatch
  const gmailUrl = `https://mail.google.com/mail/?view=cm&fs=1&to=${encodeURIComponent(recipient)}&su=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  
  // Try opening Gmail composer in new window/tab, fallback to mailto
  const win = window.open(gmailUrl, '_blank');
  if (!win || win.closed || typeof win.closed === 'undefined') {
    // Popup blocked, use standard mailto:
    const mailtoUrl = `mailto:${encodeURIComponent(recipient)}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
    window.location.href = mailtoUrl;
  }
}

/**
 * Opens WhatsApp web / app with prefilled text message for samsontsegaye26.
 */
export function openWhatsAppComposer(
  recipientHandleOrPhone: string = TARGET_WHATSAPP,
  messageText: string
) {
  // If numeric phone digits provided (e.g. 251911...), use wa.me/phone, otherwise use wa.me/?text=
  const cleanPhone = recipientHandleOrPhone.replace(/[^0-9]/g, '');
  const url = cleanPhone.length >= 9
    ? `https://wa.me/${cleanPhone}?text=${encodeURIComponent(messageText)}`
    : `https://api.whatsapp.com/send?text=${encodeURIComponent(messageText)}`;
  
  window.open(url, '_blank');
}
